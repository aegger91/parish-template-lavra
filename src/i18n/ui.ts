export function t(locale: Locale): UiDict {
  return ui[locale] ?? ui.sr;
}

export function localizedPath(locale: Locale, path: string): string {
  const clean = path.replace(/^\//, '').replace(/\/$/, '');
  return clean ? `/${locale}/${clean}/` : `/${locale}/`;
}
